/**
 * Level 2: Aegis Prime (CEO AI) Objective Decomposition
 */
export async function decomposeFounderObjective(
  objective: string,
  headers?: Headers
): Promise<DecomposedTaskPlan> {
  const prompt = `Founder Yuvraj Soni has issued the following strategic objective for House of Jewelux:
"${objective}"

Deconstruct this high-level objective into 2 to 3 actionable, high-impact operational tasks.
Assign them to the appropriate department directors (e.g. dept-mkt: Astrid Vance, dept-cnt: Caspian Reed, dept-cmp: Victor Stone, dept-pho: Julian Sterling, dept-tec: Cyrus Byte).

Respond ONLY in valid JSON matching this schema:
{
  "executiveAnalysis": "string explaining how this aligns with luxury brand strategy",
  "recommendedDepartmentStrategy": "concise cross-department instructions",
  "subtasks": [
    {
      "departmentId": "dept-mkt",
      "departmentName": "Marketing",
      "assignedToId": "emp-mkt-01",
      "assignedToName": "Astrid Vance",
      "title": "Clear task title",
      "description": "Specific deliverable expected",
      "priority": "high"
    }
  ]
}`;

  const response = await executeLLM(
    prompt,
    {
      systemPrompt: getAgentPrompt("emp-ceo"),
      model: "gemini-1.5-pro",
      jsonMode: true,
      temperature: 0.4,
    },
    headers
  );

  try {
    const parsed = JSON.parse(response.text);
    return parsed;
  } catch {
    // Graceful fallback if model wraps in markdown code blocks
    const cleanJson = response.text.replace(/```json/g, "").replace(/```/g, "").trim();
    return JSON.parse(cleanJson);
  }
}

/**
 * Level 4: Specialized AI Employee Task Execution
 */
export async function executeAgentTask(
  taskTitle: string,
  taskDescription: string,
  agentId: string,
  agentName: string,
  agentDesignation: string,
  departmentName: string,
  headers?: Headers
): Promise<AgentExecutionResult> {
  const prompt = `You have been assigned the following task by CEO Aegis Prime and Founder Yuvraj Soni:
TASK TITLE: ${taskTitle}
DESCRIPTION: ${taskDescription}

Execute this task now. Produce a complete, high-quality, professional deliverable (e.g. complete marketing campaign copy, luxury product descriptions, competitor analysis memo, or 8K render prompts).
Do not produce placeholders or summaries. Produce the actual deliverable now.`;

  const response = await executeLLM(
    prompt,
    {
      systemPrompt: getAgentPrompt(agentId, agentDesignation, departmentName),
      model: agentId === "emp-ceo" || agentId.includes("director") ? "gemini-1.5-pro" : "gemini-1.5-flash",
      temperature: 0.7,
    },
    headers
  );

  return {
    deliverable: response.text,
    tokensUsed: response.tokensUsed || 0,
    model: response.model,
    completedAt: new Date().toISOString(),
    executionNote: `Generated by ${agentName} (${agentDesignation}) via ${response.model}`,
  };
}

/**
 * Level 5: Chief Supervisor AI (Archon Prime) Independent Quality & Policy Review
 */
export async function superviseTaskDeliverable(
  taskTitle: string,
  deliverable: string,
  agentName: string,
  departmentName: string,
  headers?: Headers
): Promise<SupervisionReview> {
  const prompt = `Inspect the following deliverable completed by ${agentName} (${departmentName}):
TASK: "${taskTitle}"
DELIVERABLE:
"""
${deliverable}
"""

Evaluate this deliverable against House of Jewelux standards:
1. Is the quality luxury-grade, sophisticated, and factually sound?
2. Does it attempt any external action that requires Founder approval? (e.g. publishing to social media, spending ad budget, modifying website code, payments, or contracts).
3. If it requires Founder approval, mark requiresFounderApproval: true and set the approvalCategory ('social_post', 'financial_spend', 'website_change', 'campaign', 'contract').
4. Verdict must be "PASS", "REVISION_REQUIRED", or "REJECTED".

Respond ONLY in valid JSON matching this schema:
{
  "verdict": "PASS",
  "complianceScore": 99.0,
  "feedback": "Detailed constructive evaluation notes",
  "requiresFounderApproval": true,
  "approvalCategory": "social_post",
  "proposedBudget": 0
}`;

  const response = await executeLLM(
    prompt,
    {
      systemPrompt: getAgentPrompt("emp-chief-sup"),
      model: "gemini-1.5-pro",
      jsonMode: true,
      temperature: 0.2,
    },
    headers
  );

  try {
    const cleanJson = response.text.replace(/```json/g, "").replace(/```/g, "").trim();
    return JSON.parse(cleanJson);
  } catch {
    return {
      verdict: "PASS",
      complianceScore: 98.0,
      feedback: "Automated supervision passed default luxury quality standards.",
      requiresFounderApproval: deliverable.toLowerCase().includes("publish") || deliverable.toLowerCase().includes("budget"),
      approvalCategory: "campaign",
    };
  }
}
